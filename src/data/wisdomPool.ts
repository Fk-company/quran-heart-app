// Pick a deterministic daily set so the carousel changes content every day.
export function pickDailySet(size = 24): WisdomItem[] {
  const dayKey = Math.floor(Date.now() / 86400000); // ~UTC day index
  let seed = (dayKey * 2654435761) >>> 0;
  const pool = [...WISDOM_POOL];
  // Fisher–Yates with seeded RNG
  for (let i = pool.length - 1; i > 0; i--) {
    seed = (seed * 1664525 + 1013904223) >>> 0;
    const j = seed % (i + 1);
    [pool[i], pool[j]] = [pool[j], pool[i]];
  }
  // Ensure category diversity: take up to N, interleave by category
  const buckets: Record<string, WisdomItem[]> = {};
  pool.forEach(it => { (buckets[it.cat] ||= []).push(it); });
  const order: WisdomCategory[] = ['ayah','hadith','dhikr','dua','name','wisdom'];
  const out: WisdomItem[] = [];
  let added = true;
  while (out.length < size && added) {
    added = false;
    for (const c of order) {
      const b = buckets[c];
      if (b && b.length) { out.push(b.shift()!); added = true; if (out.length >= size) break; }
    }
  }
  return out;
}
